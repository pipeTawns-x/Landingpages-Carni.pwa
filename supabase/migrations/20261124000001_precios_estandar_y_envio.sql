-- 1. product_sizes: el pedido por pieza estandarizada.
-- ---------------------------------------------------------------------------------------------
CREATE TABLE public.product_sizes (
    id            integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    integer      NOT NULL REFERENCES public.products (id) ON DELETE CASCADE,
    grams         integer      NOT NULL,
    rounding_step numeric(4,2) NOT NULL DEFAULT 1.00,
    is_active     boolean      NOT NULL DEFAULT true,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT product_sizes_grams_range CHECK (grams BETWEEN 1 AND 50000),
    CONSTRAINT product_sizes_rounding_step_allowed CHECK (rounding_step IN (0.01, 0.10, 0.50, 1.00)),
    CONSTRAINT product_sizes_product_grams_key UNIQUE (product_id, grams)
);
-- La UNIQUE (product_id, grams) ya es el indice de la clave foranea y sirve a la consulta
-- "tamaños activos de un producto, del mas ligero al mas pesado".

COMMENT ON TABLE public.product_sizes IS
    'Tamaños estandar de un producto por kilo: "340 g cuesta $265". Precio = gramos x $/kg redondeado a rounding_step; no se guarda.';
COMMENT ON COLUMN public.product_sizes.rounding_step IS
    'Paso al que se redondea el precio, mitad hacia arriba: 1.00 al peso (340 g a $779/kg = $265), 0.01 al centavo ($264.86).';

ALTER TABLE public.product_sizes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.product_sizes FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.product_sizes TO anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.product_sizes TO authenticated, django;
-- La secuencia de la identidad nace con los privilegios por defecto del esquema (incluido anon):
