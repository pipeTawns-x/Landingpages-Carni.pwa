REVOKE ALL ON SEQUENCE public.product_sizes_id_seq FROM PUBLIC, anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.product_sizes_id_seq TO authenticated, django;
CREATE POLICY product_sizes_select_active ON public.product_sizes
    FOR SELECT TO anon, authenticated USING (is_active);
CREATE POLICY product_sizes_admin_all ON public.product_sizes
    FOR ALL TO authenticated
    USING ((SELECT public.is_admin())) WITH CHECK ((SELECT public.is_admin()));
CREATE POLICY product_sizes_django_all ON public.product_sizes
    FOR ALL TO django USING (true) WITH CHECK (true);

-- ---------------------------------------------------------------------------------------------
-- 2. delivery_zones: el envio segun los kilometros, sin importar el tamaño del pedido.
--    Una zona cubre (from_km, to_km]: el borde superior es inclusivo (SUPOSICION: la fuente solo
--    publica "0-5.5 km", "5.5-11 km"). Mas alla de la ultima zona activa no hay envio a domicilio.
--    El rango numrange usa el operador && de gist sin btree_gist.
-- ---------------------------------------------------------------------------------------------
CREATE TABLE public.delivery_zones (
    id         integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text          NOT NULL CHECK (char_length(name) BETWEEN 1 AND 60),
    from_km    numeric(5,2)  NOT NULL,
    to_km      numeric(5,2)  NOT NULL,
    fee        numeric(10,2) NOT NULL,
    is_active  boolean       NOT NULL DEFAULT true,
    created_at timestamptz   NOT NULL DEFAULT now(),
    -- En numeric, NaN es igual a NaN y mayor que todo numero: pasa `>= 0` y `> from_km`. Por eso
    -- cada CHECK lo excluye aparte (<> 'NaN'). Sin tope de fee: es una decision de producto.
    CONSTRAINT delivery_zones_from_km_not_neg CHECK (from_km >= 0 AND from_km <> 'NaN'::numeric),
    CONSTRAINT delivery_zones_range CHECK (to_km > from_km AND to_km <> 'NaN'::numeric),
    CONSTRAINT delivery_zones_fee_not_negative CHECK (fee >= 0 AND fee <> 'NaN'::numeric),
    CONSTRAINT delivery_zones_no_overlap EXCLUDE USING gist (
        numrange(from_km, to_km, '(]') WITH &&
    ) WHERE (is_active)
);

COMMENT ON TABLE public.delivery_zones IS
    'Costo de envio a domicilio por anillo de distancia: cubre (from_km, to_km]. Sin traslapes entre zonas activas; sin zona, no hay envio.';

